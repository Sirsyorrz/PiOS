import { z } from "zod";
import { AgentEventSchema, ExtensionUiRequestSchema } from "./events.ts";
import { ImageContentSchema, SessionEntrySchema } from "./messages.ts";
import { SessionStateSchema, StreamingBehaviorSchema } from "./commands.ts";

/**
 * PiOS wire protocol: the client-to-daemon envelope carried over one
 * WebSocket that multiplexes every session.
 *
 * This is deliberately not pi's RPC protocol. The daemon owns N pi sessions,
 * so every frame needs a `sessionId`, and delivery has to be idempotent across
 * reconnects, so every client-originated frame needs a `commandId`.
 */

/** Bumped on any breaking envelope change. Clients refuse a mismatch. */
export const WIRE_VERSION = 1;

const ClientBase = z.object({
  v: z.literal(WIRE_VERSION),
  /**
   * Idempotency key, generated by the client and stable across retries.
   * The daemon dedupes on it, so a redelivered prompt is not run twice.
   */
  commandId: z.string(),
  sessionId: z.string().optional(),
});

// `.extend` rather than a spread: spreading a generic shape into an object
// literal loses per-member optionality when the type is inferred.
const Envelope = <T extends z.ZodRawShape>(shape: T) => ClientBase.extend(shape);

export const ClientFrameSchema = z.discriminatedUnion("type", [
  // Must succeed before the supervisor reports `connected`.
  Envelope({ type: z.literal("hello"), deviceToken: z.string(), clientVersion: z.string() }),
  Envelope({ type: z.literal("list_sessions") }),
  Envelope({
    type: z.literal("create_session"),
    cwd: z.string(),
    name: z.string().optional(),
    /** Explicit, because pi's headless trust default is not something to inherit. */
    trustProject: z.boolean().default(false),
    model: z.string().optional(),
    /**
     * Path to an existing pi session JSONL, from `list_resumable`. Adopts that
     * transcript instead of starting an empty one, so a session begun in the
     * TUI continues here under its own id.
     */
    resumeFrom: z.string().optional(),
  }),
  /** Sessions on disk, including ones the daemon never started. */
  Envelope({
    type: z.literal("list_resumable"),
    /** Restrict to one project directory. Omitted means every project. */
    cwd: z.string().optional(),
    limit: z.number().optional(),
  }),
  Envelope({ type: z.literal("dispose_session"), sessionId: z.string() }),
  // Relaunches the same session under new trust; it never forks a new one.
  Envelope({
    type: z.literal("set_session_trust"),
    sessionId: z.string(),
    trustProject: z.boolean(),
  }),
  Envelope({
    type: z.literal("subscribe"),
    sessionId: z.string(),
    /** Last buffered event seq the client holds, for a gapless tail. */
    sinceSeq: z.number().optional(),
  }),
  Envelope({ type: z.literal("unsubscribe"), sessionId: z.string() }),
  // Resume. `since` omitted means "send everything".
  Envelope({
    type: z.literal("get_entries"),
    sessionId: z.string(),
    since: z.string().optional(),
  }),
  Envelope({
    type: z.literal("prompt"),
    sessionId: z.string(),
    /** Stable per composed message, survives app restart in the outbox. */
    messageId: z.string(),
    text: z.string(),
    images: z.array(ImageContentSchema).default([]),
    /** Mandatory while the agent streams; the daemon applies it only then. */
    streamingBehavior: StreamingBehaviorSchema.optional(),
  }),
  Envelope({ type: z.literal("interrupt"), sessionId: z.string() }),
  Envelope({
    type: z.literal("extension_ui_response"),
    sessionId: z.string(),
    requestId: z.string(),
    value: z.string().optional(),
    confirmed: z.boolean().optional(),
    cancelled: z.boolean().optional(),
  }),
  /** Activity lease: what the client wants kept warm, not a liveness ping. */
  Envelope({
    type: z.literal("activity"),
    visible: z.boolean(),
    focused: z.boolean(),
    appState: z.enum(["active", "inactive", "background"]),
    sessionIds: z.array(z.string()).default([]),
  }),
]);
export type ClientFrame = z.infer<typeof ClientFrameSchema>;

export const SessionSummarySchema = z.object({
  sessionId: z.string(),
  name: z.string().optional(),
  cwd: z.string(),
  /** `crashed` is reported, never hidden behind a silent restart. */
  status: z.enum(["idle", "running", "crashed", "disposed"]),
  trusted: z.boolean(),
  /** Durable cursor: survives restarts, covers only what pi persisted. */
  leafId: z.string().nullable(),
  /**
   * Live cursor: the newest buffered event. A client subscribes with this to
   * tail without replaying history it does not want.
   */
  lastSeq: z.number(),
  updatedAt: z.number(),
});
export type SessionSummary = z.infer<typeof SessionSummarySchema>;

export const ResumableSessionSchema = z.object({
  /** Pass back as `create_session.resumeFrom`. */
  path: z.string(),
  sessionId: z.string(),
  cwd: z.string(),
  name: z.string().optional(),
  createdAt: z.number(),
  modifiedAt: z.number(),
  messageCount: z.number(),
  preview: z.string(),
  /** Already open in the daemon; resuming it is an attach, not a new session. */
  live: z.boolean().default(false),
});
export type ResumableSessionWire = z.infer<typeof ResumableSessionSchema>;

const ServerBase = z.object({
  v: z.literal(WIRE_VERSION),
  /** Echoed from the request that caused this frame, when there was one. */
  commandId: z.string().optional(),
  sessionId: z.string().optional(),
});

const ServerEnvelope = <T extends z.ZodRawShape>(shape: T) => ServerBase.extend(shape);

export const ServerFrameSchema = z.discriminatedUnion("type", [
  ServerEnvelope({
    type: z.literal("welcome"),
    serverVersion: z.string(),
    piVersion: z.string(),
    sessions: z.array(SessionSummarySchema),
  }),
  ServerEnvelope({
    type: z.literal("resumable_sessions"),
    sessions: z.array(ResumableSessionSchema),
  }),
  ServerEnvelope({
    type: z.literal("ack"),
    commandId: z.string(),
    /** True when this command was already applied and was not run again. */
    duplicate: z.boolean().default(false),
  }),
  ServerEnvelope({
    type: z.literal("subscribed"),
    sessionId: z.string(),
    /** Seq the replay ended at; the client tails from here. */
    seq: z.number(),
    /**
     * Buffered events were evicted before the client's cursor, so the tail is
     * incomplete and it must resync with `get_entries`.
     */
    gap: z.boolean().default(false),
  }),
  ServerEnvelope({
    type: z.literal("error"),
    code: z.enum([
      "unauthorized",
      "unknown_session",
      "unknown_cursor",
      "bad_request",
      "agent_busy",
      "internal",
    ]),
    message: z.string(),
  }),
  ServerEnvelope({ type: z.literal("sessions"), sessions: z.array(SessionSummarySchema) }),
  ServerEnvelope({
    type: z.literal("session_state"),
    sessionId: z.string(),
    summary: SessionSummarySchema,
    state: SessionStateSchema.optional(),
  }),
  /** Delta reply to `get_entries`. `leafId` detects a moved branch. */
  ServerEnvelope({
    type: z.literal("entries"),
    sessionId: z.string(),
    entries: z.array(SessionEntrySchema),
    leafId: z.string().nullable(),
    /** True when the cursor was rejected and the client must drop its cache. */
    reset: z.boolean().default(false),
  }),
  /** A pi event, forwarded verbatim, tagged with its session. */
  ServerEnvelope({
    type: z.literal("agent_event"),
    sessionId: z.string(),
    /** Ring-buffer sequence, for detecting a gap in a live subscription. */
    seq: z.number(),
    event: AgentEventSchema,
  }),
  ServerEnvelope({
    type: z.literal("extension_ui_request"),
    sessionId: z.string(),
    request: ExtensionUiRequestSchema,
  }),
  /** The daemon restarted a crashed pi session and resumed from its JSONL. */
  ServerEnvelope({
    type: z.literal("session_recovered"),
    sessionId: z.string(),
    leafId: z.string().nullable(),
    reason: z.string(),
  }),
]);
export type ServerFrame = z.infer<typeof ServerFrameSchema>;

export function isWireVersionMismatch(raw: unknown): boolean {
  return (
    typeof raw === "object" &&
    raw !== null &&
    "v" in raw &&
    (raw as { v: unknown }).v !== WIRE_VERSION
  );
}
